"""Write paper/figures/curves.tex (Figures 2 and 3 of the paper) from the test results, after the
test run (checklist A16, A19). Until then the file holds placeholder boxes of the same size.

  Fig. 2 (crossover): test F1 on ViQuAD-Long against the budget ratio (4, 8, 16) for BM25, the
         PhoBERT selector, ViLatent-M, ViLatent-ME (f* of each ratio, chosen on select) and the
         learned prompt + BM25 (at ME's f*).
  Fig. 3 (fallbacks at 4×): test F1 against mean reader tokens per question for the log-prob-only
         fallback and the AiE cascade as τ varies (cascade_curve_r4.json), points for full context,
         ME, BM25 and truncation, and the τ chosen on select marked on each curve.

Usage (paper/main.tex loads pgfplots):
  python scripts/paper_figures.py --results-dir results/paper/test/long \
      --choices results/paper/select/choices.json --out paper/figures/curves.tex
"""
import argparse
import json
from pathlib import Path

LINES = [("bm25", "BM25", "black, mark=square*"), ("phobert", "PhoBERT", "gray, mark=triangle*"),
         ("vilatent_m", "ViLatent-M", "blue!60, dashed, mark=o"), ("vilatent_me", "ViLatent-ME", "blue, mark=*"),
         ("prompt", "Prompt + BM25", "red!70, dotted, mark=diamond*")]


def summary(d: Path, stem: str) -> dict | None:
    path = d / f"{stem}.summary.json"
    return json.loads(path.read_text(encoding="utf-8")) if path.exists() else None


def thin(points: list[dict], n: int = 150) -> list[dict]:
    """At most n points of a curve (sorted by tokens), always keeping both ends."""
    points = sorted(points, key=lambda p: p["mean_tokens"])
    step = max(1, len(points) // n)
    return points[::step] + ([points[-1]] if (len(points) - 1) % step else [])


def coords(pairs) -> str:
    return " ".join(f"({x:.1f},{y:.2f})" for x, y in pairs)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--results-dir", required=True, help="results/paper/test/long")
    ap.add_argument("--choices", required=True)
    ap.add_argument("--ratios", type=int, nargs="+", default=[4, 8, 16])
    ap.add_argument("--fallback-ratio", type=int, default=4)
    ap.add_argument("--out", default="paper/figures/curves.tex")
    args = ap.parse_args()

    d = Path(args.results_dir)
    choices = json.loads(Path(args.choices).read_text(encoding="utf-8"))["settings"]["long"]
    plots = []
    for key, label, style in LINES:
        pts = []
        for r in args.ratios:
            f = choices[str(r)]["f_star"]
            stem = {"vilatent_me": f"vilatent_me_f{f}", "prompt": f"prompt_bm25_f{f}"}.get(key, key)
            s = summary(d, f"{stem}_r{r}")
            if s:
                pts.append((r, s["f1"]))
        if pts:
            plots.append(f"\\addplot[{style}] coordinates {{{coords(pts)}}};\n\\addlegendentry{{{label}}}")
    r = args.fallback_ratio
    curves = json.loads((d / f"cascade_curve_r{r}.json").read_text(encoding="utf-8"))
    chosen = json.loads((d / f"cascade_r{r}.json").read_text(encoding="utf-8"))
    fall = []
    for name, label, style in (("logprob", "log-prob", "orange, thick"), ("cascade", "AiE cascade", "blue, thick")):
        pts = [(p["mean_tokens"], p["f1"]) for p in thin(curves[name])]
        fall.append(f"\\addplot[{style}] coordinates {{{coords(pts)}}};\n\\addlegendentry{{{label}}}")
        fall.append(f"\\addplot[{style.split(',')[0]}, only marks, mark=star, mark size=3pt, forget plot] "
                    f"coordinates {{({chosen[name]['mean_tokens']:.1f},{chosen[name]['f1']:.2f})}};")
    for stem, label in (("full", "full"), (f"vilatent_me_f{choices[str(r)]['f_star']}_r{r}", "ME"),
                        (f"bm25_r{r}", "BM25"), (f"truncation_r{r}", "trunc.")):
        s = summary(d, stem)
        if s:
            fall.append(f"\\addplot[black, only marks, mark=x, forget plot] coordinates "
                        f"{{({s['mean_used_tokens']:.1f},{s['f1']:.2f})}} "
                        f"node[font=\\tiny, anchor=south west] {{{label}}};")
    # 30 mm plots (+ the legend row above Fig. 2) keep the size of the 34 mm placeholder boxes, so the page
    # count does not change when the results arrive
    axis = "width=\\linewidth, height=30mm, font=\\scriptsize, legend style={font=\\tiny, draw=none, fill=none}"
    tex = f"""% Generated by scripts/paper_figures.py from {d} and {args.choices}; do not edit by hand.
\\begin{{figure}}[t]
\\centering
\\begin{{minipage}}[t]{{0.485\\textwidth}}
\\centering
\\begin{{tikzpicture}}
\\begin{{axis}}[{axis}, xlabel={{budget ratio $r$}}, ylabel={{test F1}}, xtick={{{",".join(map(str, args.ratios))}}},
  xticklabels={{{",".join(f"{x}$\\times$" for x in args.ratios)}}},
  legend style={{at={{(0.5,1.03)}}, anchor=south, legend columns=3}}]
{chr(10).join(plots)}
\\end{{axis}}
\\end{{tikzpicture}}
\\caption{{Test F1 against the ratio, ViQuAD-Long.}}
\\label{{fig:crossover}}
\\end{{minipage}}\\hfill
\\begin{{minipage}}[t]{{0.485\\textwidth}}
\\centering
\\begin{{tikzpicture}}
\\begin{{axis}}[{axis}, xmode=log, log ticks with fixed point, xlabel={{mean reader tokens per question}},
  ylabel={{test F1}}, legend pos=south east]
{chr(10).join(fall)}
\\end{{axis}}
\\end{{tikzpicture}}
\\caption{{Fallbacks at {r}$\\times$, ViQuAD-Long test; stars: $\\tau$ fixed on select.}}
\\label{{fig:fallback}}
\\end{{minipage}}
\\end{{figure}}
"""
    Path(args.out).parent.mkdir(parents=True, exist_ok=True)
    Path(args.out).write_text(tex, encoding="utf-8")
    print(f"wrote {args.out}")


if __name__ == "__main__":
    main()
